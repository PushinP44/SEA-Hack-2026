/**
 * One-off generator: apple_park_catalog_full.csv -> src/data/catalog.ts
 * Run with:  npm run gen:catalog
 *
 * The catalog is committed as a .ts module so the app has zero runtime CSV
 * parsing and the data ships in the bundle.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

const raw = readFileSync(join(root, 'apple_park_catalog_full.csv'), 'utf8')

// Minimal CSV parse: our data has no quoted commas, so split on commas is safe.
const lines = raw.split(/\r?\n/).filter((l) => l.trim().length > 0)
lines.shift() // drop header

function clean(s: string): string {
  // Repair common mojibake from the source export.
  return s.replace(/â€"/g, '–').replace(/â/g, '–').trim()
}

function slug(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

type Row = {
  id: string
  name: string
  character: string
  theme: string
  type: string
  collection: string
  salePrice: number
  regPrice: number
  inStock: boolean
  url: string
}

const rows: Row[] = []
const seen = new Set<string>()

for (const line of lines) {
  const parts = line.split(',')
  if (parts.length < 9) continue
  const url = parts[parts.length - 1]
  const availability = parts[parts.length - 2]
  const regPrice = parts[parts.length - 3]
  const salePrice = parts[parts.length - 4]
  const collection = parts[parts.length - 5]
  const type = parts[parts.length - 6]
  const theme = parts[parts.length - 7]
  const character = parts[parts.length - 8]
  const name = parts.slice(0, parts.length - 8).join(',')

  let id = slug(url.split('/products/')[1] || slug(name))
  while (seen.has(id)) id += '-x'
  seen.add(id)

  rows.push({
    id,
    name: clean(name),
    character: clean(character),
    theme: clean(theme),
    type: clean(type),
    collection: clean(collection),
    salePrice: Number(salePrice) || 0,
    regPrice: Number(regPrice) || 0,
    inStock: availability.trim().toLowerCase() === 'in stock',
    url: url.trim(),
  })
}

const out = `// AUTO-GENERATED by scripts/csv-to-catalog.ts — do not edit by hand.
export type Product = {
  id: string
  name: string
  character: string
  theme: string
  type: string
  collection: string
  salePrice: number
  regPrice: number
  inStock: boolean
  url: string
}

export const catalog: Product[] = ${JSON.stringify(rows, null, 2)}

export const byCollection = (prefix: string): Product[] =>
  catalog.filter((p) => p.collection.startsWith(prefix))
`

writeFileSync(join(root, 'src', 'data', 'catalog.ts'), out)
console.log(`Wrote src/data/catalog.ts with ${rows.length} products.`)
